import { create } from 'zustand'
import { persist } from 'zustand/middleware'

interface CartItem {
  id: string
  slug: string
  name: string
  price_krw: number
  price_usd: number | null
  image: string
  quantity: number
}

interface CartStore {
  items: CartItem[]
  isOpen: boolean
  addItem: (item: Omit<CartItem, 'quantity'>) => void
  removeItem: (id: string) => void
  updateQuantity: (id: string, quantity: number) => void
  clearCart: () => void
  openCart: () => void
  closeCart: () => void
  totalKrw: () => number
  totalUsd: () => number
  totalCount: () => number
}

export const useCartStore = create<CartStore>()(
  // 🟢 create+(persist = 창고 (스토어)
  // 🟢 persist(콜백함수) = 내용물
  persist(
    (set, get) => ({
      items: [],
      isOpen: false,
      // items, isOpen = 기억하는 값 (상태)
      addItem: (item) =>
        set((state) => {
          const existing = state.items.find((i) => i.id === item.id)
          //               =========== 현재 장바구니 배열 (담긴 상품들)
          //   ========= 찾은 객체 또는 undefined가 담김
          // 🟢 find = 그 배열을 한 칸씩 돌며 조건에 맞는 첫 요소를 찾아 리턴 (없으면 undefined [])
          // i는 배열의 각 요소 (배열을 한 칸씩 돌 때, 그 한 칸을 i에 넣어줌) -> find가 채움
          if (existing) {
            return {
              items: state.items.map((i) =>
                i.id === item.id ? { ...i, quantity: i.quantity + 1 } : i
              ),
            }
          }
          return { items: [...state.items, { ...item, quantity: 1 }] }
        }),
      removeItem: (id) =>
        set((state) => ({ items: state.items.filter((i) => i.id !== id) })),
      updateQuantity: (id, quantity) =>
        set((state) => ({
          items:
            quantity === 0
              ? state.items.filter((i) => i.id !== id)
              : state.items.map((i) => (i.id === id ? { ...i, quantity } : i)),
        })),
      clearCart: () => set({ items: [] }),
      openCart: () => set({ isOpen: true }),
      closeCart: () => set({ isOpen: false }),
      totalKrw: () =>
        get().items.reduce((sum, i) => sum + i.price_krw * i.quantity, 0),
      totalUsd: () =>
        get().items.reduce(
          (sum, i) => sum + (i.price_usd ?? 0) * i.quantity,
          0
        ),
      totalCount: () => get().items.reduce((sum, i) => sum + i.quantity, 0),
    }),
    { name: 'butter-weather-cart' }
  )
)

